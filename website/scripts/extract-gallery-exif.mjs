// Reads the shooting data out of the gallery photographs themselves and writes assets/gallery-exif.js.
// Only five fields are published: camera model, lens, aperture, shutter, ISO. Nothing else in the files (serial numbers,
// time stamps, location) is read. The photographs are only read, never changed.
//   node scripts/extract-gallery-exif.mjs          write assets/gallery-exif.js
//   node scripts/extract-gallery-exif.mjs --check  fail if the file on disk differs from what the photographs say
import {readFileSync, readdirSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const photoDir = join(site, 'assets/gallery');
const target = join(site, 'assets/gallery-exif.js');

// Minimal JPEG / TIFF reader: APP1 "Exif", IFD0, then the Exif sub-IFD.
function readExif(buffer) {
  let offset = 2;
  while (offset + 4 < buffer.length) {
    if (buffer[offset] !== 0xff) break;
    const marker = buffer[offset + 1];
    const length = buffer.readUInt16BE(offset + 2);
    if (marker === 0xe1 && buffer.toString('latin1', offset + 4, offset + 10) === 'Exif\0\0') return parseTiff(buffer.subarray(offset + 10, offset + 2 + length));
    if (marker === 0xda) break;
    offset += 2 + length;
  }
  return null;
}

function parseTiff(tiff) {
  const little = tiff.toString('latin1', 0, 2) === 'II';
  const u16 = (o) => (little ? tiff.readUInt16LE(o) : tiff.readUInt16BE(o));
  const u32 = (o) => (little ? tiff.readUInt32LE(o) : tiff.readUInt32BE(o));
  const sizes = {1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 7: 1};
  function ifd(start) {
    const tags = new Map();
    const count = u16(start);
    for (let i = 0; i < count; i++) {
      const entry = start + 2 + i * 12;
      const tag = u16(entry), type = u16(entry + 2), n = u32(entry + 4);
      const bytes = (sizes[type] || 1) * n;
      const at = bytes <= 4 ? entry + 8 : u32(entry + 8);
      let value;
      if (type === 2) value = tiff.toString('latin1', at, at + n).replace(/\0.*$/s, '').trim();
      else if (type === 3) value = u16(at);
      else if (type === 4) value = u32(at);
      else if (type === 5) value = u32(at) / u32(at + 4);
      tags.set(tag, value);
    }
    return tags;
  }
  const root = ifd(u32(4));
  const sub = root.has(0x8769) ? ifd(root.get(0x8769)) : new Map();
  return {model: root.get(0x0110), lens: sub.get(0xa434), aperture: sub.get(0x829d), exposure: sub.get(0x829a), iso: sub.get(0x8827)};
}

function shutter(seconds) {
  if (seconds >= 1) return `${Number.isInteger(seconds) ? seconds : seconds.toFixed(1)} s`;
  return `1/${Math.round(1 / seconds)} s`;
}

const entries = {};
for (const name of readdirSync(photoDir).filter((file) => /\.jpe?g$/i.test(file)).sort()) {
  const data = readExif(readFileSync(join(photoDir, name)));
  if (!data || !data.model) continue; // a photograph without shooting data simply shows nothing
  const entry = {};
  entry.camera = data.model;
  if (data.lens) entry.lens = data.lens;
  if (data.aperture) entry.aperture = `ƒ/${Number(data.aperture.toFixed(1))}`;
  if (data.exposure) entry.shutter = shutter(data.exposure);
  if (data.iso) entry.iso = `ISO ${data.iso}`;
  entries[name] = entry;
}

const output = `// Generated by scripts/extract-gallery-exif.mjs from the photographs in assets/gallery/. Do not edit by hand.\nwindow.RM_GALLERY_EXIF = ${JSON.stringify(entries, null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) {
    console.error('assets/gallery-exif.js is out of date: run node scripts/extract-gallery-exif.mjs');
    process.exit(1);
  }
  console.log(`gallery-exif.js matches the ${Object.keys(entries).length} photographs`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${target} (${Object.keys(entries).length} photographs)`);
}
